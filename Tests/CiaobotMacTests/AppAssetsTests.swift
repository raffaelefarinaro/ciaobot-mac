    /// SHA-256 of the approved brand app icon
    /// (`web/public/icons/icon-512.png` in the engine checkout, rasterised from
    /// `web/public/brand/ciaobot-icon.svg`). Pinning the bytes proves the client
    /// ships that exact artwork rather than drawing its own C.
    private static let brandIconSHA256 = "9e8b800305b8cfc7562cb0d3d52b340429ae03f77244a95739de646b9de8fcb9"

    /// The supplied full wordmark, dark ink and cream ink
    /// (`web/public/brand/ciaobot-wordmark*.png`). The connection screen shows
    /// this lockup rather than pairing the mark with typed text.
    private static let wordmarkSHA256 = "ab9897535f281d86c420d2f7e79061404054264e764fa1ccb4fd51bc972e0d84"
    private static let wordmarkLightSHA256 = "134d5314ef1f456b7de051a8f5bb77f814fa895e4b16ea08f093760d203da9c3"

    /// The generated icon follows Apple's macOS app-icon grid: a 1024 canvas
    /// with an 824-point tile at (100,100), so the Dock shows it at the same
    /// scale as an installed PWA instead of as a full-bleed square.
    private static let appIconCanvas = 1024
    private static let appIconTile = 824
    private static let appIconInset = 100

    /// The menu-bar template generated by `scripts/make-icons.swift` from the
    /// same mark geometry. It is loaded as a template image, so the menu bar
    /// applies the system tint.
    private static let trayTemplateSHA256 = "10e85977a23fe8777f5d05fa20fcbf70e592f1bd76f06c971888e77b518a9924"

    /// The brand tile and ink, from `web/public/brand/ciaobot-icon.svg` and
    /// `ciaobot-mark.svg`. The accent dots are the only painted colour.
    private static let brandTile = (red: 0xF8 / 255.0, green: 0xF4 / 255.0, blue: 0xEF / 255.0)
    private static let brandInk = (red: 0x1A / 255.0, green: 0x33 / 255.0, blue: 0x26 / 255.0)
    private static let brandAccent = (red: 0xDD / 255.0, green: 0x72 / 255.0, blue: 0x39 / 255.0)
    /// The two dots' centres in the icon's 1254 viewBox, mapped onto the tile.
    private static func dotCentre(_ x: CGFloat, _ y: CGFloat) -> (x: Int, y: Int) {
        let scale = CGFloat(appIconTile) / 1254
        return (
            Int(CGFloat(appIconInset) + x * scale),
            Int(CGFloat(appIconInset) + y * scale)
        )
    }

    func testWordmarksArePackagedAndMatchTheBrandArtwork() throws {
        for (dark, name, hash) in [
            (false, "ciaobot-wordmark.png", Self.wordmarkSHA256),
            (true, "ciaobot-wordmark-light.png", Self.wordmarkLightSHA256),
