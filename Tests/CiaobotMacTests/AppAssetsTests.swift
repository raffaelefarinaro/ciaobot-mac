    /// Kept outside the target's Resources directory: it is the reference
    /// artwork for regeneration and tests, not a file the running app loads.
    private var sourceArtworkURL: URL? {
        let url = packageRoot
            .appendingPathComponent("Sources/CiaobotMac/Artwork/app-icon-source.png")
        return FileManager.default.fileExists(atPath: url.path) ? url : nil
    }

    private func sha256(of url: URL) throws -> String {
        let data = try Data(contentsOf: url)
        return SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func makeTemporaryDirectory() throws -> URL {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("CiaobotMacTests-AppAssets-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    /// Writes the packaged wordmark where a given layout expects it.
    private func copyPackagedWordmark(to destination: URL) throws {
        try copyPackaged(AppAssets.wordmarkImageURL(dark: false), to: destination)
    }

    private func copyPackaged(_ source: URL?, to destination: URL) throws {
        let source = try XCTUnwrap(source)
        try FileManager.default.createDirectory(
            at: destination.deletingLastPathComponent(),
            withIntermediateDirectories: true
        )
        try FileManager.default.copyItem(at: source, to: destination)
    }

    // MARK: - Pixels

    private struct Pixel {
        let red: Int
        let green: Int
        let blue: Int
        let alpha: Int
    }

    /// The stored RGBA bytes in PNG order: row 0 is the top row.
    private func byte(_ bitmap: NSBitmapImageRep, _ x: Int, _ y: Int) -> Pixel {
        guard bitmap.samplesPerPixel == 4,
              bitmap.bitsPerSample == 8,
              let data = bitmap.bitmapData else {
            return Pixel(red: -1, green: -1, blue: -1, alpha: -1)
        }
        let offset = y * bitmap.bytesPerRow + x * 4
        return Pixel(
            red: Int(data[offset]),
            green: Int(data[offset + 1]),
            blue: Int(data[offset + 2]),
            alpha: Int(data[offset + 3])
        )
    }

    private func assertColour(
        _ bitmap: NSBitmapImageRep,
        _ x: Int,
        _ y: Int,
        _ expected: (red: Double, green: Double, blue: Double),
        _ what: String,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        let pixel = byte(bitmap, x, y)
        XCTAssertEqual(Double(pixel.red) / 255, expected.red, accuracy: 0.01,
                       "The \(what) at \(x),\(y) is not the brand colour", file: file, line: line)
        XCTAssertEqual(Double(pixel.green) / 255, expected.green, accuracy: 0.01,
                       "The \(what) at \(x),\(y) is not the brand colour", file: file, line: line)
        XCTAssertEqual(Double(pixel.blue) / 255, expected.blue, accuracy: 0.01,
                       "The \(what) at \(x),\(y) is not the brand colour", file: file, line: line)
    }
