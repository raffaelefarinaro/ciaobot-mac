            // resolution, so NSImage.size is not the artwork size.
            let image = try XCTUnwrap(NSBitmapImageRep(data: data))
            XCTAssertEqual(image.pixelsWide, 1402)
            XCTAssertEqual(image.pixelsHigh, 324)
        }
        XCTAssertNotNil(AppAssets.wordmarkImage, "The connection screen could not decode the wordmark.")
        XCTAssertNotNil(AppAssets.wordmarkLightImage, "The dark appearance wordmark did not decode.")
    }

